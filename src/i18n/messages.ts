const catalogs: Record<UiLanguage, Record<MessageKey, string>> = { de, en, fr, fa }

export function translate(
  lang: UiLanguage,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = catalogs[lang][key] ?? catalogs.de[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

export function isRtlUi(lang: UiLanguage): boolean {
  return lang === 'fa'
}
